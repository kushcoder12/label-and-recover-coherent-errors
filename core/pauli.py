"""Pauli algebra helpers for the RC-label study.

Dense (2^n x 2^n) building blocks used to construct and propagate error
generators (CLAUDE.md §4). Convention: 1-indexed qubits, big-endian, matching
operator_on_state.py. Use dense operators for small n only.
"""

import numpy as np

from .operator_on_state import single_qubit_op

# Single-qubit Pauli matrices (CLAUDE.md §2.1).
_PAULI = {
    "I": np.eye(2, dtype=complex),
    "X": np.array([[0, 1], [1, 0]], dtype=complex),
    "Y": np.array([[0, -1j], [1j, 0]], dtype=complex),
    "Z": np.array([[1, 0], [0, -1]], dtype=complex),
}


def pauli(label):
    """Return the 2x2 Pauli matrix for label in {'I','X','Y','Z'} (CLAUDE.md §2.1)."""
    try:
        return _PAULI[label].copy()
    except KeyError:
        raise ValueError(f"unknown Pauli label {label!r}; expected one of I,X,Y,Z")


def commutator(A, B):
    """[A, B] = A@B - B@A."""
    return A @ B - B @ A


def anticommutator(A, B):
    """{A, B} = A@B + B@A."""
    return A @ B + B @ A


def propagate_generator(G, W):
    """Heisenberg push of generator G through unitary W: W @ G @ W^dagger (CLAUDE.md §4).

    If a coherent error exp(-i theta G) sits *before* a later unitary W that maps
    it toward the output frame, the error in the output frame is generated by
    W G W^dagger. Used to build the propagated generators G-tilde_ell (§2.3, §2.5).
    """
    return W @ G @ W.conj().T


def pauli_string(labels):
    """Full 2^n x 2^n operator for a Pauli string given as a list/str of labels.

    labels[0] acts on qubit 1 (most significant, big-endian) via Kronecker
    product: pauli_string('XZ') = X (x) Z. For small n only.
    """
    ops = [pauli(l) for l in labels]
    result = ops[0]
    for o in ops[1:]:
        result = np.kron(result, o)
    return result


def expectation(state, Op):
    """<state|Op|state> (real part) for a dense 2^n x 2^n operator Op."""
    return np.vdot(state, Op @ state).real


def expectation_single_qubit(state, op2x2, p, n):
    """<state|op_p|state> for a single-qubit operator on qubit p (1-indexed).

    Uses the sparse single_qubit_op engine instead of building the full
    2^n x 2^n matrix. Equivalent to expectation(state, embed(op2x2)).
    """
    return np.vdot(state, single_qubit_op(state, op2x2, p, n)).real
